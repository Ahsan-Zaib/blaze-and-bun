export const products: Product[] = seeds.map((seed) => ({
  ...seed,
  slug: slug(seed.name),
  optionGroups: seed.optionGroups ?? [],
}));

export function getProduct(idOrSlug: string): Product | undefined {
  return products.find((p) => p.id === idOrSlug || p.slug === idOrSlug);
}

export function productsInCategory(category: string): Product[] {
  if (category === "deals") return products.filter((p) => p.compareAtPrice);
  if (category === "new") return products.filter((p) => p.badges.includes("new"));
  return products.filter((p) => p.category === category);
}

export const bestSellers = products.filter((p) => p.badges.includes("popular")).slice(0, 4);
export const featured = products.filter((p) => p.badges.includes("chef") || p.badges.includes("new")).slice(0, 4);
